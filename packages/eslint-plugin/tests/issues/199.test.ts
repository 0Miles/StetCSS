import { ESLint } from 'eslint'
import { mkdtempSync, rmSync, statSync, utimesSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, expect, test } from 'vitest'
import plugin from '../../src'
import resolveContext from '../../src/utils/resolve-context'

/**
 * Dates the files' last modification ten seconds back, as for files saved well before a lint, and
 * waits until their change time lies in the past, so the project manifest cache may keep them.
 */
function settle(...files: string[]) {
  const past = new Date(Date.now() - 10_000)
  for (const file of files) utimesSync(file, past, past)
  const newest = Math.max(...files.map((file) => statSync(file).ctimeMs))
  while (Date.now() <= newest) { /* a millisecond at most */ }
}

function createWorkspaceESLint(cwd: string) {
  return new ESLint({
    cwd,
    overrideConfigFile: true,
    overrideConfig: [
      {
        files: ['**/*.jsx'],
        plugins: {
          '@stet-css': plugin
        },
        languageOptions: {
          parserOptions: {
            ecmaVersion: 2022,
            sourceType: 'module',
            ecmaFeatures: {
              jsx: true
            }
          }
        },
        rules: {
          '@stet-css/no-invalid-classes': ['error', { disallowUnknownClass: true }]
        }
      }
    ]
  })
}

async function lintMessages(cwd: string) {
  const [result] = await createWorkspaceESLint(cwd).lintFiles('index.jsx')
  return result.messages.map((message) => message.message)
}

const unknownBadge = 'Unknown StetCSS class "fixture-badge". It is not generated by the active manifest.'

let cwd: string

beforeEach(() => {
  cwd = mkdtempSync(join(tmpdir(), 'stet-css-eslint-199-'))
  writeFileSync(join(cwd, 'index.jsx'), `<div className="fixture-badge"></div>`)
})

afterEach(() => {
  rmSync(cwd, { force: true, recursive: true })
})

/**
 * Fault (#199): the plugin kept each workspace's manifest for the whole process, so in an editor's
 * ESLint server or eslint_d a utility just added to the CSS entry stayed "unknown" until the
 * process restarted, even through a new `ESLint` instance.
 *
 * Reverse check: keeping the derived CSS per workspace directory again, as before #199
 * (`src/utils/resolve-context.ts`), turns this test and the imported-file one red, nothing else.
 */
test('lints against the edited CSS entry without restarting the process', async () => {
  const entryPath = join(cwd, 'index.css')
  writeFileSync(entryPath, '@import "@stet-css/core";\n@components { fixture-button { display: inline-flex; } }')
  settle(entryPath)
  expect(await lintMessages(cwd)).toStrictEqual([unknownBadge])

  writeFileSync(entryPath, '@import "@stet-css/core";\n@components { fixture-badge { display: inline-flex; } }')
  expect(await lintMessages(cwd)).toStrictEqual([])
})

/**
 * Fault (#199): the same staleness for a file the entry imports, which is where projects usually
 * keep their components and tokens.
 *
 * Reverse check: the same change as above turns this test red with it. The plugin does not track
 * imported files itself; it relies on the dependencies the project manifest cache stamps.
 */
test('lints against an edited file the CSS entry imports', async () => {
  const entryPath = join(cwd, 'index.css')
  const componentsPath = join(cwd, 'components.css')
  writeFileSync(entryPath, '@import "@stet-css/core";\n@import "./components.css";')
  writeFileSync(componentsPath, '@components { fixture-button { display: inline-flex; } }')
  settle(entryPath, componentsPath)
  expect(await lintMessages(cwd)).toStrictEqual([unknownBadge])

  writeFileSync(componentsPath, '@components { fixture-badge { display: inline-flex; } }')
  expect(await lintMessages(cwd)).toStrictEqual([])
})

/**
 * Guards: the other half of #199. With nothing changed, every rule on every file must reuse the
 * manifest and the CSS built from it, or a long-running ESLint recompiles the project per file.
 * Trade-off (testing.md 6): reads `resolveContext` directly and compares the CSS instance, because
 * a rebuilt instance lints exactly like the reused one.
 *
 * Reverse check: dropping `cache: true` from the manifest load in `src/utils/resolve-context.ts`
 * turns only this test red.
 */
test('reuses the CSS while the entry and its imports keep their stamps', () => {
  const entryPath = join(cwd, 'index.css')
  const componentsPath = join(cwd, 'components.css')
  writeFileSync(entryPath, '@import "@stet-css/core";\n@import "./components.css";')
  writeFileSync(componentsPath, '@components { fixture-badge { display: inline-flex; } }')
  settle(entryPath, componentsPath)
  const context = { cwd, filename: join(cwd, 'index.jsx'), options: [], settings: {} } as any

  const first = resolveContext(context).css
  expect(first.definedUtilities.some((utility) => utility.name === 'fixture-badge')).toBe(true)
  expect(resolveContext(context).css).toBe(first)
})

/**
 * Guards: right after an edit the project manifest cache keeps nothing for two seconds, since a
 * coarse file timestamp could hide the next edit. Every rule on a file linted then must still share
 * one compile (about 90 ms each), or an editor linting while the developer types recompiles the
 * project once per rule on every keystroke.
 * Trade-off (testing.md 6): reads `resolveContext` directly and compares the CSS instance, as above.
 *
 * Reverse check: resolving the CSS per call instead of per `context.sourceCode` in
 * `src/utils/resolve-context.ts` turns only this test red.
 */
test('builds the CSS once per linted file while a fresh edit keeps the manifest uncached', () => {
  writeFileSync(join(cwd, 'index.css'), '@import "@stet-css/core";\n@components { fixture-badge { display: inline-flex; } }')
  const sourceCode = {}
  const context = { cwd, filename: join(cwd, 'index.jsx'), sourceCode, options: [], settings: {} } as any

  expect(resolveContext(context).css).toBe(resolveContext({ ...context }).css)
})
