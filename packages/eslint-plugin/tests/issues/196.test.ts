import sortClasses from '../../src/rules/sort-classes'
import noInvalidClasses from '../../src/rules/no-invalid-classes'
import { jsxTester } from '../testers'

const vueParser = await import('vue-eslint-parser')

/**
 * Autofixes write cooked (decoded) class lists back at raw source offsets. When a literal's
 * source differs from its value (CRLF in a template, a line continuation, an escape, an HTML
 * entity), the fix must keep the source's own spelling or not fix at all.
 */
jsxTester.run('#196 sort-classes maps decoded class lists back to source', sortClasses, {
  valid: [],
  invalid: [
    {
      // espree, which parses Vue <script> blocks, reports template raw text with CRLF normalized to LF
      name: 'CRLF line breaks inside a template literal stay CRLF',
      code: '<script>clsx(`\r\nfg:white\r\nbg:black\r\n`)</script>',
      output: '<script>clsx(`\r\nbg:black\r\nfg:white\r\n`)</script>',
      errors: [{ messageId: 'invalidClassOrder' }],
      filename: 'test.vue',
      languageOptions: { parser: vueParser }
    },
    {
      name: 'a line continuation keeps the string terminated',
      code: 'clsx("fg:white\\\n bg:black")',
      output: 'clsx("bg:black\\\n fg:white")',
      errors: [{ messageId: 'invalidClassOrder' }]
    },
    {
      name: 'an escaped class keeps its escape when it moves',
      code: 'clsx("fg:white \\x62g:black")',
      output: 'clsx("\\x62g:black fg:white")',
      errors: [{ messageId: 'invalidClassOrder' }]
    },
    {
      name: 'an HTML entity in a Vue expression is reported without a fix',
      code: `<template><div :class="['fg:white&#32;bg:black']"></div></template>`,
      output: null,
      errors: [{ messageId: 'invalidClassOrder' }],
      filename: 'test.vue',
      languageOptions: { parser: vueParser }
    }
  ]
})

jsxTester.run('#196 no-invalid-classes checks the decoded class', noInvalidClasses, {
  valid: [
    {
      code: 'clsx("\\x62lock")',
      options: [{ disallowUnknownClass: true }] as any
    }
  ],
  invalid: [
    {
      code: 'clsx("\\x62lockk")',
      errors: [{
        messageId: 'disallowUnknownClass',
        data: { message: 'Unknown StetCSS class "blockk". It is not generated by the active manifest.' }
      }],
      options: [{ disallowUnknownClass: true }] as any
    }
  ]
})
