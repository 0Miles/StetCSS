import { ESLint } from 'eslint'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { expect, test } from 'vitest'
import plugin from '../src'
import isSameOrChildPath from '../src/utils/is-same-or-child-path'

/**
 * Guards: a front-end developer who still has `manifest` in the `@stet-css` ESLint settings
 * gets an error that points them to the CSS entry. Without it, ESLint silently ignores the
 * setting and lints against the CSS entry instead, so utilities and tokens defined only in
 * that setting get reported as unknown with no hint why.
 *
 * Reverse check: making `src/utils/resolve-context.ts` check `manifests` instead of
 * `manifest` (the setting is ignored again) fails only this test.
 */
test('rejects the removed manifest setting and points to the CSS entry', async () => {
  const eslint = new ESLint({
    overrideConfigFile: true,
    overrideConfig: [
      {
        files: ['**/*.jsx'],
        plugins: {
          '@stet-css': plugin
        },
        languageOptions: {
          parserOptions: {
            ecmaVersion: 2022,
            sourceType: 'module',
            ecmaFeatures: {
              jsx: true
            }
          }
        },
        settings: {
          '@stet-css': {
            manifest: { version: 1 }
          }
        },
        rules: {
          '@stet-css/sort-classes': 'error'
        }
      }
    ]
  })

  await expect(eslint.lintText(`<div className="block"></div>`, { filePath: 'index.jsx' }))
    .rejects.toThrow(/"manifest" setting[\s\S]*remove it[\s\S]*CSS entry/)
})

test('uses project-level CSS manifest entries from the ESLint workspace', async () => {
  const cwd = mkdtempSync(join(tmpdir(), 'master-css-eslint-'))

  try {
    writeFileSync(join(cwd, 'index.css'), `
      @master entry;

      @components {
        fixture-button {
          display: inline-flex;
        }
      }
    `)
    writeFileSync(join(cwd, 'index.jsx'), `<div className="fixture-button zzz"></div>`)

    const eslint = new ESLint({
      cwd,
      overrideConfigFile: true,
      overrideConfig: [
        {
          files: ['**/*.jsx'],
          plugins: {
            '@stet-css': plugin
          },
          languageOptions: {
            parserOptions: {
              ecmaVersion: 2022,
              sourceType: 'module',
              ecmaFeatures: {
                jsx: true
              }
            }
          },
          rules: {
            '@stet-css/no-invalid-classes': [
              'error',
              {
                disallowUnknownClass: true
              }
            ]
          }
        }
      ]
    })

    const [result] = await eslint.lintFiles('index.jsx')

    expect(result.messages.map((message) => message.message)).toStrictEqual([
      'Unknown Master CSS class "zzz". It is not generated by the active manifest.'
    ])
  } finally {
    rmSync(cwd, { force: true, recursive: true })
  }
})

test('does not match sibling workspace path prefixes', () => {
  const cwd = mkdtempSync(join(tmpdir(), 'master-css-eslint-'))

  try {
    const workspaceDir = join(cwd, 'packages', 'app')

    expect(isSameOrChildPath(workspaceDir, join(workspaceDir, 'index.jsx'))).toBe(true)
    expect(isSameOrChildPath(workspaceDir, join(cwd, 'packages', 'app-kit', 'index.jsx'))).toBe(false)
  } finally {
    rmSync(cwd, { force: true, recursive: true })
  }
})
