import rule from '../src/rules/no-invalid-classes'
import { RuleTester } from '@typescript-eslint/rule-tester'
import { createCustomManifestTester, createUndeclaredModeTester, jsxTester } from './testers'

jsxTester.run('invalid', rule, {
  valid: [
    {
      code: `<div class="m:2x p:2x bg:black fg:white font:1.5rem">Simple, basic</div>`,
    },
    {
      code: `<div class={\`f:\${ fontSize }px\`}>TemplateLiteral</div>`,
    },
    {
      code: `<div class="{content:'';block}::after@light"></div>`,
    },
  ],
  invalid: [
    {
      code: `<div class="bg:black text-decoration:bad() rrr">Simple, basic</div>`,
      errors: [
        {
          messageId: 'invalidClass',
          data: {
            message: 'Class "text-decoration:bad()" emits invalid CSS: Invalid value for `text-decoration-color` property.'
          }
        },
        {
          messageId: 'disallowUnknownClass',
          data: {
            message: 'Unknown Master CSS class "rrr". It is not generated by the active manifest.'
          }
        }
      ],
      options: [
        {
          disallowUnknownClass: true
        }
      ] as any
    },
    {
      code: `<div class="bg:black text-decoration:bad() rrr">Simple, basic</div>`,
      errors: [
        { messageId: 'invalidClass' },
      ]
    },
    {
      code: `<div class="a c d hello:world text-decoration:bad() mt:0 mt:0@sm">Error class</div>`,
      errors: [
        { messageId: 'disallowUnknownClass' },
        { messageId: 'disallowUnknownClass' },
        { messageId: 'disallowUnknownClass' },
        { messageId: 'disallowUnknownClass' },
        { messageId: 'invalidClass' }
      ],
      options: [
        {
          disallowUnknownClass: true
        }
      ] as any
    },
    {
      code: `<div class="a c d hello:world text-decoration:bad() mt:0 mt:0@sm">Error class</div>`,
      errors: [
        { messageId: 'invalidClass' }
      ]
    },
  ]
})

createCustomManifestTester().run('invalid', rule, {
  valid: [],
  invalid: [
    {
      code: `<div class="btn rrr bg:black text-decoration:bad()">Simple, basic</div>`,
      errors: [
        { messageId: 'disallowUnknownClass' },
        { messageId: 'invalidClass' }
      ],
      options: [
        {
          disallowUnknownClass: true
        }
      ] as any
    },
    {
      code: `<div class="btn a c d hello:world text-decoration:bad() mt:0 mt:0@sm">Error class</div>`,
      errors: [
        { messageId: 'disallowUnknownClass' },
        { messageId: 'disallowUnknownClass' },
        { messageId: 'disallowUnknownClass' },
        { messageId: 'disallowUnknownClass' },
        { messageId: 'invalidClass' }
      ],
      options: [
        {
          disallowUnknownClass: true
        }
      ] as any
    },
  ],
})

/**
 * Prevents (#69): a class naming a mode the project does not declare (`@dark` in a project that
 * declares only `@theme sepia {}`) crashing the rule, and with it the whole ESLint run, instead
 * of being reported at the class; reported without `disallowUnknownClass`, since it is a
 * misconfigured mode rather than an unknown class. The neighbouring class still lints normally.
 * Reverse-checked: removing the catch in validator `validate.ts` turns this case into a crash.
 */
createUndeclaredModeTester().run('undeclared mode', rule, {
  valid: [
    { code: `<div class="fg:red@sepia fg:blue">Declared mode</div>` }
  ],
  invalid: [
    {
      code: `<div class="fg:red@dark fg:blue">Undeclared mode</div>`,
      errors: [
        { messageId: 'invalidClass', column: 13, endColumn: 24 }
      ]
    }
  ]
})
